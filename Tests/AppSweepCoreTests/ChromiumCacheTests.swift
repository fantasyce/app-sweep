        try setNamespace(namespace,app:f.app)
        let app = try AppInspector.inspect(f.app)
        XCTAssertEqual(try ChromiumCacheRule.roots(home:f.home,app:app,inventory:[app]),[],"Confirmed absence of both runtime roots is empty, not an unreadable profile")
    }
    func testFlatBundlePeerDoesNotRequireMacContentsDirectory() throws {
        let f = try makeFixture(); defer { try? f.clean() }
        let peer = f.home + "/Applications/Preview.app"
        try FileManager.default.createDirectory(atPath:peer,withIntermediateDirectories:true)
        let id = "org.example.flatpreview"
        let identity = ApplicationIdentity(path:peer,name:"Preview",bundleIdentifier:id,signed:false,protectedReason:"Embedded component")
        let app = try AppInspector.inspect(f.app)
        func write(_ namespace: String?) throws {
            var info:[String:Any] = ["CFBundleIdentifier":id,"CFBundlePackageType":"APPL"]
            if let namespace { info["CrProductDirName"] = namespace }
            try PropertyListSerialization.data(fromPropertyList:info,format:.xml,options:0).write(to:URL(fileURLWithPath:peer + "/Info.plist"))
        }
        try write(nil)
        XCTAssertEqual(try ChromiumCacheRule.roots(home:f.home,app:app,inventory:[app,identity]),[cache(f)])
        try write("Independent/Browser")
        XCTAssertEqual(try ChromiumCacheRule.roots(home:f.home,app:app,inventory:[app,identity]),[cache(f)])
        try write(namespace)
        XCTAssertThrowsError(try ChromiumCacheRule.roots(home:f.home,app:app,inventory:[app,identity]))
    }
    private func relocateNamespace(_ f: NativeAcceptanceTests.NativeFixture, to value: String) throws {
        for base in ["/Library/Application Support/","/Library/Caches/"] {
            try FileManager.default.moveItem(atPath:f.home + base + namespace,toPath:f.home + base + value)
        }
        try setNamespace(value,app:f.app)
    }
    private func combined(_ f: NativeAcceptanceTests.NativeFixture) -> SweepEngine {
        SweepEngine(policy:SafetyPolicy(home:f.home,acceptedPlatform:true,validatedRules:[rule,CacheDomainRule.name,"signed-application-v1"]),vaultPath:f.home + "/Library/Application Support/App Sweep/Recovery",fixture:false)
    }
    func testExactIDCannotClaimAnotherRuntimeNamespace() async throws {
