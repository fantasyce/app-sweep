    func testExplicitNamespaceCannotClaimAnotherBrowsersImplicitDefault() throws {
        let f = try makeFixture(); defer { try? f.clean() }
        for base in ["/Library/Application Support/","/Library/Caches/"] {
            try FileManager.default.createDirectory(atPath:f.home + base + "Google",withIntermediateDirectories:true)
        }
        try relocateNamespace(f,to:"Google/Chrome")
        let peer = f.home + "/Applications/Default Browser.app"
        try FileManager.default.copyItem(atPath:f.app,toPath:peer)
        let url = URL(fileURLWithPath:peer + "/Contents/Info.plist")
        var info = try XCTUnwrap(try PropertyListSerialization.propertyList(from:Data(contentsOf:url),format:nil) as? [String:Any])
        info["CFBundleIdentifier"] = "com.google.Chrome"
        info.removeValue(forKey:"CrProductDirName")
