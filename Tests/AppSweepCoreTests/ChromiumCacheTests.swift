@testable import AppSweepCore

final class ChromiumCacheTests: XCTestCase, @unchecked Sendable {
    private let rule = "chromium-registered-profile-cache-v1"
    private let identifier = "org.example.sweepfixture"
    private let namespace = "Fixture Vendor/Browser Beta"

    private func makeFixture() throws -> NativeAcceptanceTests.NativeFixture {
        let f = try NativeAcceptanceTests.NativeFixture(additionalRules:[rule])
        try setNamespace(namespace, app:f.app)
        let support = f.home + "/Library/Application Support/" + namespace
        let fm = FileManager.default
        try fm.createDirectory(atPath:support + "/Default",withIntermediateDirectories:true)
        try JSONSerialization.data(withJSONObject:["profile":["info_cache":["Default":["name":"Disposable"]]]]).write(to:URL(fileURLWithPath:support + "/Local State"))
        try JSONSerialization.data(withJSONObject:["profile":["name":"Disposable"]]).write(to:URL(fileURLWithPath:support + "/Default/Preferences"))
        try Data("persistent bookmarks must survive".utf8).write(to:URL(fileURLWithPath:support + "/Default/Bookmarks"))
        let root = cache(f)
        for name in ["Cache","Code Cache"] {
            try fm.createDirectory(atPath:root + "/" + name,withIntermediateDirectories:true)
            try Data((name + " independently generated bytes").utf8).write(to:URL(fileURLWithPath:root + "/" + name + "/opaque-payload"))
        }
        return f
    }
    private func cache(_ f: NativeAcceptanceTests.NativeFixture) -> String { f.home + "/Library/Caches/" + namespace + "/Default" }
    private func setNamespace(_ value: String, app: String, id: String? = nil) throws {
        let url = URL(fileURLWithPath:app + "/Contents/Info.plist")
        var info = try XCTUnwrap(try PropertyListSerialization.propertyList(from:Data(contentsOf:url),format:nil) as? [String:Any])
        info["CrProductDirName"] = value
        if let id { info["CFBundleIdentifier"] = id }
        try PropertyListSerialization.data(fromPropertyList:info,format:.xml,options:0).write(to:url)
        _ = try BoundedProcess.run("/usr/bin/codesign",arguments:["--force","--sign","-",app],timeout:10)
    }
    private func fresh(_ f: NativeAcceptanceTests.NativeFixture) -> SweepEngine {
        SweepEngine(policy:SafetyPolicy(home:f.home,acceptedPlatform:true,validatedRules:[rule,"signed-application-v1"]),vaultPath:f.home + "/Library/Application Support/App Sweep/Recovery",fixture:false)
    }
    private func items(_ report: ScanReport) -> [Candidate] { report.selectableCandidates(includeUserData:false).filter { $0.rule == rule } }
    private func persistent(_ f: NativeAcceptanceTests.NativeFixture) throws -> String {
        try VerifiedFileStream.digest(SafeFilesystem.snapshot(f.home + "/Library/Application Support/" + namespace + "/Default/Bookmarks"))
    }

    func testNamespaceRequiresExplicitCanonicalRuntimeMetadata() {
        XCTAssertEqual(ChromiumCacheRule.namespace(info:["CrProductDirName":namespace]),namespace)
        for invalid in ["", "/private/var/folders", "../Other", "Vendor//Browser", "Vendor/../Browser", "Vendor/./Browser", "Vendor/Browser/", "Vendor\nBrowser", "com.apple.Safari", "Vendor/Keychains", "App Sweep", "Vendor/a.keychain-db"] {
            XCTAssertNil(ChromiumCacheRule.namespace(info:["CrProductDirName":invalid]),invalid)
        }
        XCTAssertNil(ChromiumCacheRule.namespace(info:["CFBundleName":"Browser Beta"]))
    }
    func testRegisteredProfilesAreBoundedLeavesRatherThanPaths() throws {
        let valid = try JSONSerialization.data(withJSONObject:["profile":["info_cache":["Default":[:],"Profile 1":[:]]]])
        XCTAssertEqual(ChromiumCacheRule.profiles(data:valid),["Default","Profile 1"])
        for leaf in ["../Other", "/Default", "A/B", ".", "..", "com.apple.TCC", "Keychains"] {
            let data = try JSONSerialization.data(withJSONObject:["profile":["info_cache":[leaf:[:]]]])
            XCTAssertNil(ChromiumCacheRule.profiles(data:data),leaf)
        }
        XCTAssertNil(ChromiumCacheRule.profiles(data:Data("{}".utf8)))
    }
