    func testUnreadableIndependentPreferencesDoNotHideVerifiedUninstallCache() async throws {
        let f = try makeFixture(), fm = FileManager.default
        let preferences = f.home + "/Library/Preferences"
        try fm.createDirectory(atPath:preferences,withIntermediateDirectories:true)
        try Data("preserve unreadable settings".utf8).write(to:URL(fileURLWithPath:preferences + "/" + identifier + ".plist"))
        defer { try? fm.setAttributes([.posixPermissions:0o700],ofItemAtPath:preferences); try? f.clean() }
        try fm.setAttributes([.posixPermissions:0],ofItemAtPath:preferences)
        try await f.waitUntilUnused(f.app)
        let report = try await f.engine.scanApplication(f.app), caches = items(report)
        XCTAssertFalse(report.complete,"Denied preferences must stay explicitly unconfirmed")
        XCTAssertEqual(caches.count,2,"Independent cache ownership was complete: " + report.unconfirmedIssues.joined(separator:"; "))
        guard caches.count == 2 else { return }
        let selection = report.selectableCandidates(includeUserData:false).filter { $0.category == .application || $0.rule == rule }
        let plan = try await f.engine.makePlan(reportID:report.id,selected:Set(selection.map(\.id)),includeUserData:false)
        XCTAssertFalse(plan.items.contains { $0.userData })
        let batch = try await f.engine.execute(planID:plan.id)
        XCTAssertEqual(batch.status,.isolated,batch.issue ?? ""); guard batch.status == .isolated else { return }
        try await f.waitForIsolatedObjects(batch)
        let restored = try await fresh(f).restore(batchID:batch.id)
        XCTAssertEqual(restored.status,.restored,restored.entries.compactMap(\.message).joined(separator:"; "))
        try fm.setAttributes([.posixPermissions:0o700],ofItemAtPath:preferences)
        XCTAssertEqual(try Data(contentsOf:URL(fileURLWithPath:preferences + "/" + identifier + ".plist")),Data("preserve unreadable settings".utf8))
    }
