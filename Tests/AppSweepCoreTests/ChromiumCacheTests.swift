    func testRegisteredCacheSelectionIsolationAndFreshRecoveryPreserveProfile() async throws {
        let f = try makeFixture(); defer { try? f.clean() }
        let root = cache(f), original = try SafeFilesystem.snapshot(root), data = try persistent(f)
        let report = try await f.engine.scanJunk(), selected = items(report)
        let retained = report.candidates.filter { $0.rule == rule }.compactMap(\.retentionReason)
        XCTAssertEqual(Set(selected.map(\.path)),[root + "/Cache",root + "/Code Cache"],(report.issues + retained).joined(separator:"; "))
        guard selected.count == 2 else { return }
        do { _ = try await f.engine.makePlan(reportID:report.id,selected:[selected[0].id],includeUserData:false); XCTFail("Incomplete cache group must be refused") } catch { }
        let plan = try await f.engine.makePlan(reportID:report.id,selected:Set(selected.map(\.id)),includeUserData:false)
        let batch = try await f.engine.execute(planID:plan.id)
        XCTAssertEqual(batch.status,.isolated,batch.issue ?? ""); XCTAssertTrue(batch.hasIndependentBackups)
        XCTAssertEqual(try SafeDirectory(path:root).ownIdentity.inode,original.identity.inode)
        XCTAssertEqual(try persistent(f),data)
        let restored = try await fresh(f).restore(batchID:batch.id)
        XCTAssertEqual(restored.status,.restored,restored.entries.compactMap(\.message).joined(separator:"; "))
        let current = try SafeFilesystem.snapshot(root)
        XCTAssertEqual(current.tree.map(\.relative),original.tree.map(\.relative))
        for (a,b) in zip(current.tree,original.tree) { XCTAssertTrue(a.identity.sameObject(as:b.identity),a.relative) }
        XCTAssertEqual(try persistent(f),data)
    }
