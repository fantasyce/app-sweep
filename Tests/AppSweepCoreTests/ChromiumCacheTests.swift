    func testNewMemberAndRegenerationConflictKeepWholeGroupUntouched() async throws {
        let f = try makeFixture(); defer { try? f.clean() }
        let root = cache(f), report = try await f.engine.scanJunk(), selected = items(report)
        XCTAssertEqual(selected.count,2); guard selected.count == 2 else { return }
        let plan = try await f.engine.makePlan(reportID:report.id,selected:Set(selected.map(\.id)),includeUserData:false)
        let new = root + "/new-member"
        try Data("new member".utf8).write(to:URL(fileURLWithPath:new))
        do { _ = try await f.engine.execute(planID:plan.id); XCTFail("Changed group must not be partly moved") } catch { }
        XCTAssertTrue(FileManager.default.fileExists(atPath:root + "/Cache/opaque-payload"))
        let next = try await f.engine.scanJunk(), all = items(next)
        let reviewed = try await f.engine.makePlan(reportID:next.id,selected:Set(all.map(\.id)),includeUserData:false)
        let batch = try await f.engine.execute(planID:reviewed.id)
        XCTAssertEqual(batch.status,.isolated); guard batch.status == .isolated else { return }
        try Data("regenerated fresh bytes".utf8).write(to:URL(fileURLWithPath:new))
        let conflict = try await fresh(f).restore(batchID:batch.id)
        XCTAssertEqual(conflict.status,.needsAttention)
        XCTAssertFalse(FileManager.default.fileExists(atPath:root + "/Cache"))
        XCTAssertEqual(try Data(contentsOf:URL(fileURLWithPath:new)),Data("regenerated fresh bytes".utf8))
    }
