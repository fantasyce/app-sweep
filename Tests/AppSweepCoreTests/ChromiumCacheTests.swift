    func testMissingIsolatedCacheReconstructsFromIndependentBytes() async throws {
        let f = try makeFixture(); defer { try? f.clean() }
        let root = cache(f), old = try SafeFilesystem.snapshot(root + "/Cache"), original = try Data(contentsOf:URL(fileURLWithPath:root + "/Cache/opaque-payload")), saved = try persistent(f)
        let report = try await f.engine.scanJunk(), selected = items(report)
        XCTAssertEqual(selected.count,2); guard selected.count == 2 else { return }
        let plan = try await f.engine.makePlan(reportID:report.id,selected:Set(selected.map(\.id)),includeUserData:false)
        let batch = try await f.engine.execute(planID:plan.id)
        XCTAssertEqual(batch.status,.isolated); guard batch.status == .isolated else { return }
        let item = try XCTUnwrap(batch.entries.first { $0.original.path == root + "/Cache" })
        let objects = try SafeDirectory(path:f.home + "/Library/Application Support/App Sweep/Recovery/" + batch.id.uuidString + "/" + batch.objectsDirectory)
        let snapshot = try SafeFilesystem.snapshot(objects.path + "/" + item.id.uuidString)
        XCTAssertTrue(SafeFilesystem.removeVerified(in:objects,name:item.id.uuidString,identity:snapshot.identity,contents:snapshot.tree),"Remove only the exact registered disposable isolated object to simulate cache reclaim")
        let restored = try await fresh(f).restore(batchID:batch.id)
        XCTAssertEqual(restored.status,.restored,restored.entries.compactMap(\.message).joined(separator:"; "))
        XCTAssertNotEqual(try SafeDirectory(path:root + "/Cache").ownIdentity.inode,old.identity.inode)
        XCTAssertEqual(try Data(contentsOf:URL(fileURLWithPath:root + "/Cache/opaque-payload")),original)
        XCTAssertEqual(try persistent(f),saved)
    }
