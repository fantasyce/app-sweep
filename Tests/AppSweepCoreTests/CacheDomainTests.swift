    private let rule = "cache-exact-domain-v1"
    private func fixture() throws -> NativeAcceptanceTests.NativeFixture { try .init(additionalRules: [rule]) }
    private func engine(_ f: NativeAcceptanceTests.NativeFixture, failure: FailurePoint? = nil) -> SweepEngine {
        SweepEngine(policy: SafetyPolicy(home: f.home, acceptedPlatform: true, validatedRules: [rule]), vaultPath: f.home + "/Library/Application Support/App Sweep/Recovery", failurePoint: failure, fixture: false)
    }
    func testCacheRecoveryPreflightsTheWholeGroupBeforeRestoringAnyMember() async throws {
        let f = try fixture(); defer { try? f.clean() }; try f.generate()
        let root = f.home + "/Library/Caches/org.example.sweepfixture"
        try FileManager.default.createDirectory(atPath: root + "/z-empty", withIntermediateDirectories: true)
        let report = try await f.engine.scanJunk(), items = report.selectableCandidates(includeUserData: false).filter { $0.rule == rule }
        let plan = try await f.engine.makePlan(reportID: report.id, selected: Set(items.map(\.id)), includeUserData: false), batch = try await f.engine.execute(planID: plan.id)
        XCTAssertEqual(batch.status, .isolated)
        try Data("fresh regenerated bytes".utf8).write(to: URL(fileURLWithPath: root + "/payload"))
        let conflict = try await f.engine.restore(batchID: batch.id)
        XCTAssertEqual(conflict.status, .needsAttention)
        XCTAssertFalse(FileManager.default.fileExists(atPath: root + "/z-empty"), "A later conflict must not leave an earlier cache member restored")
        XCTAssertEqual(try String(contentsOfFile: root + "/payload", encoding: .utf8), "fresh regenerated bytes")
    }
