    func testFoundationConsumerCachesRegenerateAsACompleteDomain() async throws {
        let f = try CacheRuleTests.Fixture(); defer { try? f.clean() }
        let sentinel = f.home + "/Library/Application Support/notes.txt"
        try Data("preserve user data".utf8).write(to: URL(fileURLWithPath: sentinel))
        let root = try SafeDirectory(path: f.root).ownIdentity
        let engine = SweepEngine(policy: SafetyPolicy(home: f.home, acceptedPlatform: true, validatedRules: [rule]), vaultPath: f.home + "/Library/Application Support/App Sweep/Recovery", fixture: false)
        for round in 0..<2 {
            let report = try await engine.scanJunk(), items = report.selectableCandidates(includeUserData: false).filter { $0.rule == rule }
            XCTAssertTrue(items.contains { $0.path == f.root + "/Cache.db" }, report.candidates.compactMap(\.retentionReason).joined(separator: "; "))
            XCTAssertTrue(items.contains { $0.path == f.path })
            let plan = try await engine.makePlan(reportID: report.id, selected: Set(items.map(\.id)), includeUserData: false)
            let batch = try await engine.execute(planID: plan.id)
            XCTAssertEqual(batch.status, .isolated, batch.issue ?? "")
            XCTAssertTrue(batch.hasIndependentBackups)
            XCTAssertEqual(try SafeDirectory(path: f.root).ownIdentity.inode, root.inode)
            XCTAssertEqual(try String(contentsOfFile: sentinel, encoding: .utf8), "preserve user data")
            if round == 0 {
                let restored = try await engine.restore(batchID: batch.id)
                XCTAssertEqual(restored.status, .restored, restored.entries.compactMap(\.message).joined(separator: "; "))
                XCTAssertEqual(try BoundedProcess.run(f.executable, arguments: ["--read", f.root], timeout: 10).trimmingCharacters(in: .whitespacesAndNewlines), "524288")
                try f.sql("PRAGMA wal_checkpoint(TRUNCATE)")
            } else {
                try f.generate()
                let conflict = try await engine.restore(batchID: batch.id)
                XCTAssertEqual(conflict.status, .needsAttention)
                XCTAssertEqual(try BoundedProcess.run(f.executable, arguments: ["--read", f.root], timeout: 10).trimmingCharacters(in: .whitespacesAndNewlines), "524288")
                XCTAssertEqual(try SafeDirectory(path: f.root).ownIdentity.inode, root.inode)
            }
        }
    }
    func testCacheDomainCannotIssueAPartialDatabasePlan() async throws {
        let f = try fixture(); defer { try? f.clean() }; try f.generate()
        let root = f.home + "/Library/Caches/org.example.sweepfixture"
        try Data("owned sidecar".utf8).write(to: URL(fileURLWithPath: root + "/payload-wal"))
        let report = try await f.engine.scanJunk()
        let items = report.selectableCandidates(includeUserData: false).filter { $0.rule == rule }
        XCTAssertEqual(items.count, 2)
        let first = try XCTUnwrap(items.first)
        XCTAssertEqual(report.selectionIDs(for: first.id, includeUserData: false), Set(items.map(\.id)))
        XCTAssertFalse(report.selectionIsComplete([first.id], includeUserData: false))
        do { _ = try await f.engine.makePlan(reportID: report.id, selected: [first.id], includeUserData: false); XCTFail("A database and its namespace peers must not be split") } catch { }
        let complete = try await f.engine.makePlan(reportID: report.id, selected: Set(items.map(\.id)), includeUserData: false)
        XCTAssertEqual(complete.items.count, 2)
    }
    func testInterruptedArchiveRegistrationRemainsReadableAfterRestoreAndPurge() async throws {
        let f = try fixture(); defer { try? f.clean() }; try f.generate()
        let failing = engine(f, failure: .interruptAfterBackup), report = try await failing.scanJunk()
        let item = try XCTUnwrap(report.selectableCandidates(includeUserData: false).first { $0.rule == rule })
        let plan = try await failing.makePlan(reportID: report.id, selected: [item.id], includeUserData: false)
        do { _ = try await failing.execute(planID: plan.id); XCTFail("Expected the controlled archive-registration interruption") } catch { }
        XCTAssertTrue(FileManager.default.fileExists(atPath: item.path))
        let fresh = engine(f), batches = try await fresh.recoveryBatches(), batch = try XCTUnwrap(batches.first)
        XCTAssertEqual(batch.entries.first?.backupPending, true)
        let restored = try await fresh.restore(batchID: batch.id)
        XCTAssertEqual(restored.status, .restored)
        let reopened = engine(f), persisted = try await reopened.recoveryBatches()
        XCTAssertEqual(persisted.first?.status, .restored)
        let purged = try await reopened.purge(batchID: batch.id, confirmation: "永久清空 " + batch.id.uuidString)
        XCTAssertEqual(purged.status, .purged)
        XCTAssertTrue(FileManager.default.fileExists(atPath: item.path))
    }
    func testIndependentArchiveRecoversWhenTheMovedCacheDirectoryDisappears() async throws {
        let f = try fixture(); defer { try? f.clean() }
        let path = f.home + "/Library/Caches/org.example.sweepfixture/database"
        try FileManager.default.createDirectory(atPath: path + "/nested", withIntermediateDirectories: true)
        let bytes = Data("owned cache database bytes".utf8)
        try bytes.write(to: URL(fileURLWithPath: path + "/nested/data"))
        let original = try SafeFilesystem.snapshot(path)
        let report = try await f.engine.scanJunk()
        let item = try XCTUnwrap(report.selectableCandidates(includeUserData: false).first { $0.path == path && $0.rule == rule })
        let plan = try await f.engine.makePlan(reportID: report.id, selected: [item.id], includeUserData: false)
        let batch = try await f.engine.execute(planID: plan.id)
        XCTAssertEqual(batch.status, .isolated, batch.issue ?? "")
        XCTAssertTrue(batch.hasIndependentBackups, "Moving a cache inode is not an independent recovery copy")
        guard batch.hasIndependentBackups else { return }
        let vault = f.home + "/Library/Application Support/App Sweep/Recovery"
        let stored = vault + "/" + batch.id.uuidString + "/" + batch.objectsDirectory + "/" + item.id.uuidString
        // Explicit fault injection on this test's own disposable object only.
        try FileManager.default.removeItem(atPath: stored)
        let fresh = SweepEngine(policy: SafetyPolicy(home: f.home, acceptedPlatform: true, validatedRules: [rule]), vaultPath: vault, fixture: false)
        let restored = try await fresh.restore(batchID: batch.id)
        XCTAssertEqual(restored.status, .restored, restored.entries.compactMap(\.message).joined(separator: "; "))
        XCTAssertEqual(try Data(contentsOf: URL(fileURLWithPath: path + "/nested/data")), bytes)
        XCTAssertNotEqual(try SafeDirectory(path: path).ownIdentity.inode, original.identity.inode)
        XCTAssertTrue(restored.hasIndependentBackups)
    }
    func testGeneralCacheContentsMoveRestoreAndRegenerateWhileRootAndPreferencesRemain() async throws {
        let f = try fixture(); defer { try? f.clean() }; try f.generate()
        let root = f.home + "/Library/Caches/org.example.sweepfixture"
        let pref = f.home + "/Library/Preferences/org.example.sweepfixture.plist"
        let rootIdentity = try SafeDirectory(path: root).ownIdentity, prefs = try Data(contentsOf: URL(fileURLWithPath: pref))
        let report = try await f.engine.scanJunk()
        let items = report.selectableCandidates(includeUserData: false).filter { $0.rule == rule }
        XCTAssertEqual(items.map(\.path), [root + "/payload"])
        guard items.count == 1 else { return }
        let plan = try await f.engine.makePlan(reportID: report.id, selected: Set(items.map(\.id)), includeUserData: false)
        let batch = try await f.engine.execute(planID: plan.id)
        XCTAssertEqual(batch.status, .isolated, batch.issue ?? "")
        XCTAssertEqual(try SafeDirectory(path: root).ownIdentity.inode, rootIdentity.inode)
        XCTAssertEqual(try SafeDirectory(path: root).ownIdentity.device, rootIdentity.device)
        XCTAssertEqual(try Data(contentsOf: URL(fileURLWithPath: pref)), prefs)
        let restored = try await f.restoreWhenUnused(batch)
        XCTAssertEqual(restored.status, .restored)
        let next = try await f.engine.scanJunk(), selected = next.selectableCandidates(includeUserData: false).filter { $0.rule == rule }
        let secondPlan = try await f.engine.makePlan(reportID: next.id, selected: Set(selected.map(\.id)), includeUserData: false)
        let second = try await f.engine.execute(planID: secondPlan.id)
        XCTAssertEqual(second.status, .isolated)
        try f.generate()
        XCTAssertEqual(try String(contentsOfFile: root + "/payload", encoding: .utf8), "HTTP fixture content")
        let conflict = try await f.engine.restore(batchID: second.id)
        XCTAssertEqual(conflict.status, .needsAttention)
        XCTAssertEqual(try SafeDirectory(path: root).ownIdentity.inode, rootIdentity.inode)
        XCTAssertEqual(try SafeDirectory(path: root).ownIdentity.device, rootIdentity.device)
    }
    func testUnsafeOrSharedNamespacesRemainUntouched() async throws {
        for mode in ["link", "hardlink", "keychain", "duplicate", "unsigned"] {
            let f = try fixture(); defer { try? f.clean() }; try f.generate()
            let root = f.home + "/Library/Caches/org.example.sweepfixture", outside = f.home + "/outside"
            try Data("private data".utf8).write(to: URL(fileURLWithPath: outside))
            if mode == "link" { try FileManager.default.createSymbolicLink(atPath: root + "/escape", withDestinationPath: outside) }
            if mode == "hardlink" { try FileManager.default.linkItem(atPath: outside, toPath: root + "/shared") }
            if mode == "keychain" { try FileManager.default.copyItem(atPath: outside, toPath: root + "/secret.keychain-db") }
            if mode == "duplicate" { try FileManager.default.copyItem(atPath: f.app, toPath: f.home + "/Applications/Peer.app") }
            if mode == "unsigned" { _ = try BoundedProcess.run("/usr/bin/codesign", arguments: ["--remove-signature", f.app], timeout: 10) }
            let report = try await f.engine.scanJunk()
            XCTAssertFalse(report.selectableCandidates(includeUserData: false).contains { $0.rule == rule }, mode)
            XCTAssertEqual(try String(contentsOfFile: outside, encoding: .utf8), "private data")
            XCTAssertTrue(FileManager.default.fileExists(atPath: root + "/payload"))
        }
    }
