    func testFullyContainedCacheHardLinksCanIsolateRestoreReconstructAndPurge() async throws {
        let f = try fixture(); defer { try? f.clean() }
        let root = f.home + "/Library/Caches/org.example.sweepfixture/blobstore"
        try FileManager.default.createDirectory(atPath: root + "/Blobs", withIntermediateDirectories: true)
        try FileManager.default.createDirectory(atPath: root + "/Records", withIntermediateDirectories: true)
        let bytes = Data("owned shared blob bytes".utf8), blob = root + "/Blobs/body", record = root + "/Records/body"
        try bytes.write(to: URL(fileURLWithPath: blob))
        try FileManager.default.linkItem(atPath: blob, toPath: record)
        let report = try await f.engine.scanJunk()
        let candidates = report.selectableCandidates(includeUserData: false).filter { $0.rule == rule && $0.path == root }
        XCTAssertEqual(candidates.count, 1, "A complete directory owns both links; do not reject normal cache structure")
        guard let item = candidates.first else { return }
        let plan = try await f.engine.makePlan(reportID: report.id, selected: [item.id], includeUserData: false)
        let moved = try await f.engine.execute(planID: plan.id)
        XCTAssertEqual(moved.status, .isolated, moved.issue ?? "")
        let restored = try await f.engine.restore(batchID: moved.id)
        XCTAssertEqual(restored.status, .restored)
        let a = try SafeDirectory(path: root + "/Blobs").identity("body"), b = try SafeDirectory(path: root + "/Records").identity("body")
        XCTAssertEqual(a.inode, b.inode); XCTAssertEqual(a.links, 2)
        let next = try await f.engine.scanJunk(), secondItem = try XCTUnwrap(next.selectableCandidates(includeUserData: false).first { $0.path == root })
        let nextPlan = try await f.engine.makePlan(reportID: next.id, selected: [secondItem.id], includeUserData: false), second = try await f.engine.execute(planID: nextPlan.id)
        guard second.status == .isolated, second.hasIndependentBackups else { XCTFail("Independent archive required before reclaim injection"); return }
        let vault = f.home + "/Library/Application Support/App Sweep/Recovery"
        try FileManager.default.removeItem(atPath: vault + "/" + second.id.uuidString + "/" + second.objectsDirectory + "/" + secondItem.id.uuidString)
        let fresh = engine(f), rebuilt = try await fresh.restore(batchID: second.id)
        XCTAssertEqual(rebuilt.status, .restored, rebuilt.entries.compactMap(\.message).joined(separator: "; "))
        let c = try SafeDirectory(path: root + "/Blobs").identity("body"), d = try SafeDirectory(path: root + "/Records").identity("body")
        XCTAssertEqual(c.inode, d.inode); XCTAssertEqual(c.links, 2); XCTAssertNotEqual(c.inode, a.inode)
        XCTAssertEqual(try Data(contentsOf: URL(fileURLWithPath: blob)), bytes)
        let lastReport = try await fresh.scanJunk(), lastItem = try XCTUnwrap(lastReport.selectableCandidates(includeUserData: false).first { $0.path == root })
        let lastPlan = try await fresh.makePlan(reportID: lastReport.id, selected: [lastItem.id], includeUserData: false), lastBatch = try await fresh.execute(planID: lastPlan.id)
        let purged = try await fresh.purge(batchID: lastBatch.id, confirmation: "永久清空 " + lastBatch.id.uuidString)
        XCTAssertEqual(purged.status, .purged, purged.issue ?? "")
        XCTAssertFalse(FileManager.default.fileExists(atPath: root))
    }
