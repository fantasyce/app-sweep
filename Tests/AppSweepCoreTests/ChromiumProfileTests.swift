#if os(macOS)
import Foundation
import XCTest
@testable import AppSweepCore

final class ChromiumProfileTests: XCTestCase, @unchecked Sendable {
    private let identifier = "org.example.sweepfixture"
    private let namespace = "Independent Runtime/Disposable Browser"
    private func source(_ f: NativeAcceptanceTests.NativeFixture) -> String { f.home + "/Library/Application Support/" + namespace }
    private func cache(_ f: NativeAcceptanceTests.NativeFixture) -> String { f.home + "/Library/Caches/" + namespace + "/Default" }
    private func sign(_ app: String, namespace: String, identifier: String? = nil) throws {
        let path = app + "/Contents/Info.plist"
        var info = try XCTUnwrap(try PropertyListSerialization.propertyList(from:Data(contentsOf:URL(fileURLWithPath:path)),format:nil) as? [String:Any])
        info["CrProductDirName"] = namespace
        if let identifier { info["CFBundleIdentifier"] = identifier }
        try PropertyListSerialization.data(fromPropertyList:info,format:.xml,options:0).write(to:URL(fileURLWithPath:path))
        _ = try BoundedProcess.run("/usr/bin/codesign",arguments:["--force","--sign","-",app],timeout:10)
    }
    private func fixture() throws -> NativeAcceptanceTests.NativeFixture {
        let f = try NativeAcceptanceTests.NativeFixture(additionalRules:[ChromiumProfileRule.name,ChromiumCacheRule.name])
        try sign(f.app,namespace:namespace)
        let fm = FileManager.default, support = source(f)
        try fm.createDirectory(atPath:support + "/Default",withIntermediateDirectories:true)
        try JSONSerialization.data(withJSONObject:["profile":["info_cache":["Default":["name":"Disposable"]]]]).write(to:URL(fileURLWithPath:support + "/Local State"))
        try JSONSerialization.data(withJSONObject:["profile":["name":"Disposable"]]).write(to:URL(fileURLWithPath:support + "/Default/Preferences"))
        try Data("personal bookmarks and history are not junk".utf8).write(to:URL(fileURLWithPath:support + "/Default/Bookmarks"))
        for name in ["Cache","Code Cache"] {
            try fm.createDirectory(atPath:cache(f) + "/" + name,withIntermediateDirectories:true)
            try Data((name + " regenerated bytes").utf8).write(to:URL(fileURLWithPath:cache(f) + "/" + name + "/payload"))
        }
        return f
    }
    private func fresh(_ f: NativeAcceptanceTests.NativeFixture, failurePoint: FailurePoint? = nil) -> SweepEngine {
        SweepEngine(policy:SafetyPolicy(home:f.home,acceptedPlatform:true,validatedRules:[ChromiumProfileRule.name,ChromiumCacheRule.name,"signed-application-v1"]),vaultPath:f.home + "/Library/Application Support/App Sweep/Recovery",failurePoint:failurePoint,fixture:false)
    }
    private func selected(_ report: ScanReport) -> [Candidate] {
        report.selectableCandidates(includeUserData:true).filter { $0.category == .application || [ChromiumCacheRule.name,ChromiumProfileRule.name].contains($0.rule) }
    }
    private func isolate(_ f: NativeAcceptanceTests.NativeFixture) async throws -> RecoveryManifest {
        try await f.waitUntilUnused(f.app)
        let report = try await f.engine.scanApplication(f.app), items = selected(report)
        XCTAssertEqual(items.count,4,report.unconfirmedIssues.joined(separator:"; ") + report.candidates.compactMap(\.retentionReason).joined(separator:"; "))
        guard items.count == 4 else { throw SweepError.incomplete("Expected independent body, two cache members and whole user profile") }
        let plan = try await f.engine.makePlan(reportID:report.id,selected:Set(items.map(\.id)),includeUserData:true)
        let batch = try await f.engine.execute(planID:plan.id)
        XCTAssertEqual(batch.status,.isolated,batch.issue ?? "")
        guard batch.status == .isolated else { throw SweepError.incomplete(batch.issue ?? "Isolation failed") }
        try await f.waitForIsolatedObjects(batch)
        return batch
    }
    func testRegisteredProfileIsExplicitUserDataAndNeverDefaultJunk() async throws {
        let f = try fixture(); defer { try? f.clean() }
        let before = try SafeFilesystem.snapshot(source(f)), report = try await f.engine.scanApplication(f.app)
        let data = try XCTUnwrap(report.selectableCandidates(includeUserData:true).first { $0.rule == ChromiumProfileRule.name })
        XCTAssertEqual(data.path,source(f)); XCTAssertEqual(data.category,.userData); XCTAssertFalse(data.selectedByDefault)
        XCTAssertFalse(report.selectableCandidates(includeUserData:false).contains { $0.id == data.id })
        do { _ = try await f.engine.makePlan(reportID:report.id,selected:Set(selected(report).map(\.id)),includeUserData:false); XCTFail("Personal profile requires explicit opt-in") } catch { }
        let junk = try await f.engine.scanJunk()
        XCTAssertFalse(junk.candidates.contains { $0.rule == ChromiumProfileRule.name })
        try SafeFilesystem.verify(before)
    }
    func testWholeUninstallRestoresProfileBeforeDependentCacheAndOriginalApplication() async throws {
        let f = try fixture(); defer { try? f.clean() }
        let support = try SafeFilesystem.snapshot(source(f)), caches = try SafeFilesystem.snapshot(cache(f))
        let bookmarks = try Data(contentsOf:URL(fileURLWithPath:source(f) + "/Default/Bookmarks"))
        let batch = try await isolate(f)
        XCTAssertFalse(FileManager.default.fileExists(atPath:f.app)); XCTAssertFalse(FileManager.default.fileExists(atPath:source(f)))
        XCTAssertTrue(try FileManager.default.contentsOfDirectory(atPath:cache(f)).isEmpty)
        XCTAssertEqual(batch.entries.last?.original.rule,ChromiumProfileRule.name,"Profile evidence moves last and restores first")
        let restored = try await fresh(f).restore(batchID:batch.id)
        XCTAssertEqual(restored.status,.restored,restored.entries.compactMap(\.message).joined(separator:"; "))
        guard restored.status == .restored else { return }
        XCTAssertEqual(try SafeFilesystem.snapshot(source(f)).tree,support.tree)
        let current = try SafeFilesystem.snapshot(cache(f)).tree
        XCTAssertEqual(current.map(\.relative),caches.tree.map(\.relative))
        for (now,before) in zip(current,caches.tree) { XCTAssertTrue(now.identity.sameObject(as:before.identity),now.relative) }
        for name in ["Cache","Code Cache"] {
            XCTAssertEqual(try Data(contentsOf:URL(fileURLWithPath:cache(f) + "/" + name + "/payload")),Data((name + " regenerated bytes").utf8))
        }
        XCTAssertEqual(try Data(contentsOf:URL(fileURLWithPath:source(f) + "/Default/Bookmarks")),bookmarks)
        XCTAssertTrue(AppInspector.signatureMatches(path:f.app,identifier:identifier))
    }
    func testRegeneratedProfileStopsWholeRecoveryWithoutRestoringCache() async throws {
        let f = try fixture(); defer { try? f.clean() }
        let batch = try await isolate(f), fm = FileManager.default
        try fm.createDirectory(atPath:source(f),withIntermediateDirectories:true)
        let new = source(f) + "/new-personal-data"
        try Data("new data must never be overwritten".utf8).write(to:URL(fileURLWithPath:new))
        let before = try SafeFilesystem.snapshot(new), restored = try await fresh(f).restore(batchID:batch.id)
        XCTAssertEqual(restored.status,.needsAttention)
        try SafeFilesystem.verify(before)
        XCTAssertTrue(try fm.contentsOfDirectory(atPath:cache(f)).isEmpty)
        XCTAssertFalse(fm.fileExists(atPath:f.app))
    }
    func testChangedIsolatedProfileCannotSupplyCacheRegistrationEvidence() async throws {
        let f = try fixture(); defer { try? f.clean() }
        let batch = try await isolate(f), entry = try XCTUnwrap(batch.entries.first { $0.original.rule == ChromiumProfileRule.name })
        let stored = f.home + "/Library/Application Support/App Sweep/Recovery/" + batch.id.uuidString + "/objects.noindex/" + entry.id.uuidString
        try Data("changed stored personal data".utf8).write(to:URL(fileURLWithPath:stored + "/Default/Bookmarks"))
        do {
            let restored = try await fresh(f).restore(batchID:batch.id)
            XCTAssertEqual(restored.status,.needsAttention)
        } catch { }
        XCTAssertTrue(try FileManager.default.contentsOfDirectory(atPath:cache(f)).isEmpty)
        XCTAssertFalse(FileManager.default.fileExists(atPath:source(f)))
        XCTAssertFalse(FileManager.default.fileExists(atPath:f.app))
    }
    func testSharedNamespaceProfileIsRetained() async throws {
        let f = try fixture(); defer { try? f.clean() }
        let peer = f.home + "/Applications/Shared Browser.app", fm = FileManager.default
        try fm.copyItem(atPath:f.app,toPath:peer)
        try sign(peer,namespace:namespace,identifier:"org.example.sharedbrowser")
        let shared = try await f.engine.scanApplication(f.app)
        XCTAssertFalse(selected(shared).contains { $0.rule == ChromiumProfileRule.name })
    }
    func testProtectedProfileIsRetainedWithoutDependingOnASharedPeer() async throws {
        let f = try fixture(); defer { try? f.clean() }
        let protected = source(f) + "/Default/secret.keychain-db"
        try Data("protected security content".utf8).write(to:URL(fileURLWithPath:protected))
        let guarded = try await f.engine.scanApplication(f.app)
        XCTAssertFalse(selected(guarded).contains { $0.rule == ChromiumProfileRule.name })
    }
    func testLinkedProfileIsRetainedWithoutDependingOnASharedPeer() async throws {
        let f = try fixture(); defer { try? f.clean() }
        try FileManager.default.createSymbolicLink(atPath:source(f) + "/Default/foreign-link",withDestinationPath:f.home + "/Library/Preferences")
        let linked = try await f.engine.scanApplication(f.app)
        XCTAssertFalse(selected(linked).contains { $0.rule == ChromiumProfileRule.name })
    }
    func testSharedWritePermissionsCannotAuthorizePersonalProfileRemoval() throws {
        let f = try fixture(); defer { try? f.clean() }
        let path = source(f) + "/Default/Bookmarks"
        try FileManager.default.setAttributes([.posixPermissions:0o666],ofItemAtPath:path)
        XCTAssertThrowsError(try ChromiumProfileRule.verify(path:source(f),home:f.home,identifier:identifier,applicationPath:f.app,signaturePath:nil))
        try FileManager.default.setAttributes([.posixPermissions:0o600],ofItemAtPath:path)
        _ = try BoundedProcess.run("/bin/chmod",arguments:["+a","everyone allow write",path],timeout:3)
        XCTAssertThrowsError(try ChromiumProfileRule.verify(path:source(f),home:f.home,identifier:identifier,applicationPath:f.app,signaturePath:nil))
    }
    func testExactIDSupportConventionCannotDuplicateRegisteredProfileAuthority() async throws {
        let f = try fixture(); defer { try? f.clean() }
        let root = f.home + "/Library/Application Support/" + identifier
        try FileManager.default.moveItem(atPath:source(f),toPath:root)
        try sign(f.app,namespace:identifier)
        let engine = SweepEngine(policy:SafetyPolicy(home:f.home,acceptedPlatform:true,validatedRules:[ChromiumProfileRule.name,SupportDomainRule.name,"signed-application-v1"]),vaultPath:f.home + "/Library/Application Support/App Sweep/Recovery",fixture:false)
        let report = try await engine.scanApplication(f.app)
        let data = report.selectableCandidates(includeUserData:true).filter { $0.path == root }
        XCTAssertEqual(data.map(\.rule),[ChromiumProfileRule.name],"One personal profile must not appear twice under competing ownership conventions")
    }
    func testForgedProfileTargetCannotProvideAnAlternateRecoveryDestination() async throws {
        let f = try fixture(); defer { try? f.clean() }
        let batch = try await isolate(f)
        let path = f.home + "/Library/Application Support/App Sweep/Recovery/" + batch.id.uuidString + "/manifest.json"
        var manifest = try XCTUnwrap(try JSONSerialization.jsonObject(with:Data(contentsOf:URL(fileURLWithPath:path))) as? [String:Any])
        var entries = try XCTUnwrap(manifest["entries"] as? [[String:Any]])
        let index = try XCTUnwrap(entries.firstIndex { ($0["original"] as? [String:Any])?["rule"] as? String == ChromiumProfileRule.name })
        var original = try XCTUnwrap(entries[index]["original"] as? [String:Any])
        let foreign = f.home + "/Library/Application Support/Other Browser"
        original["path"] = foreign; entries[index]["original"] = original; manifest["entries"] = entries
        try JSONSerialization.data(withJSONObject:manifest,options:[.sortedKeys]).write(to:URL(fileURLWithPath:path))
        do {
            let restored = try await fresh(f).restore(batchID:batch.id)
            XCTAssertEqual(restored.status,.needsAttention)
        } catch { }
        XCTAssertFalse(FileManager.default.fileExists(atPath:foreign))
        XCTAssertFalse(FileManager.default.fileExists(atPath:source(f)))
        XCTAssertTrue(try FileManager.default.contentsOfDirectory(atPath:cache(f)).isEmpty)
    }
    func testFailureBeforeSecondMoveRestoresBodyAndKeepsProfileAndCacheIntact() async throws {
        let f = try fixture(); defer { try? f.clean() }; try await f.waitUntilUnused(f.app)
        let before = try SafeFilesystem.snapshot(source(f)), caches = try SafeFilesystem.snapshot(cache(f))
        let engine = fresh(f,failurePoint:.beforeSecondMove), report = try await engine.scanApplication(f.app)
        let items = selected(report)
        XCTAssertEqual(items.count,4); guard items.count == 4 else { return }
        let plan = try await engine.makePlan(reportID:report.id,selected:Set(items.map(\.id)),includeUserData:true)
        let batch = try await engine.execute(planID:plan.id)
        XCTAssertEqual(batch.status,.rolledBack,batch.issue ?? "")
        try SafeFilesystem.verify(before); try SafeFilesystem.verify(caches)
        XCTAssertTrue(AppInspector.signatureMatches(path:f.app,identifier:identifier))
    }
    func testProfileAndBodyRestoreWithoutRequiringCacheSelection() async throws {
        let f = try fixture(); defer { try? f.clean() }; try await f.waitUntilUnused(f.app)
        let caches = try SafeFilesystem.snapshot(cache(f)), profile = try SafeFilesystem.snapshot(source(f))
        let report = try await f.engine.scanApplication(f.app)
        let items = selected(report).filter { $0.rule != ChromiumCacheRule.name }
        XCTAssertEqual(items.count,2); guard items.count == 2 else { return }
        let plan = try await f.engine.makePlan(reportID:report.id,selected:Set(items.map(\.id)),includeUserData:true)
        let batch = try await f.engine.execute(planID:plan.id)
        XCTAssertEqual(batch.status,.isolated,batch.issue ?? ""); guard batch.status == .isolated else { return }
        try await f.waitForIsolatedObjects(batch)
        let restored = try await fresh(f).restore(batchID:batch.id)
        XCTAssertEqual(restored.status,.restored,restored.entries.compactMap(\.message).joined(separator:"; "))
        try SafeFilesystem.verify(caches)
        XCTAssertEqual(try SafeFilesystem.snapshot(source(f)).tree,profile.tree)
    }
    func testCompletedRecoveryDoesNotRevalidateOrOverwriteNewPersonalEdits() async throws {
        let f = try fixture(); defer { try? f.clean() }
        let batch = try await isolate(f), restored = try await fresh(f).restore(batchID:batch.id)
        XCTAssertEqual(restored.status,.restored); guard restored.status == .restored else { return }
        let path = source(f) + "/Default/Bookmarks"
        try Data("new personal edits after completed recovery".utf8).write(to:URL(fileURLWithPath:path))
        let before = try SafeFilesystem.snapshot(path), repeated = try await fresh(f).restore(batchID:batch.id)
        XCTAssertEqual(repeated.status,.restored,"A completed batch is a no-op; later personal edits are not a recovery failure")
        try SafeFilesystem.verify(before)
    }
}
